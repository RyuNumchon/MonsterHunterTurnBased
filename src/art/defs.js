/** Picks an icon shape for a material name. 'g:x' = reuse gathering icon x. */
export function matType(n) {
  if (/ORE|CRYSTAL/.test(n)) return 'g:mining';
  if (/BONE/.test(n)) return 'g:bones';
  if (/MEAT/.test(n)) return 'meat';
  if (/FANG|CLAW|TAIL|HEAD|SCREAMER/.test(n)) return 'claw';
  if (/MARROW|SAC|GEM|RUBY|TEAR/.test(n)) return 'gem';
  if (/SCALE|HIDE|PELT|WEBBING/.test(n)) return 'scale';
  if (/SHELL|PLATE/.test(n)) return 'shell';
  if (/FISH|ARROWANA/.test(n)) return 'g:fish';
  if (/BUG|HUSK/.test(n)) return 'g:bugs';
  if (/HONEY/.test(n)) return 'g:honey';
  if (/MUSHROOM|PARASHROOM/.test(n)) return 'g:mushrooms';
  if (/BERRY/.test(n)) return 'g:berries';
  if (/WOOD/.test(n)) return 'g:misc';
  return 'g:plants';
}